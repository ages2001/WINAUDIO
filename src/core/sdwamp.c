/* indirect read of a 32-bit DSP / high voltage block register */
static u32 r20_pr_read(struct sdwdev *s, u32 reg)
{
    static const u32 cmd[] = { 0xC483, 0x80, 0xC482, 0x40, 0xC481, 0x0C, 0xC480, 0x10 };
    u32 v = 0, a;
    sdw_seq(s, cmd, ARRAY_SIZE(cmd) / 2);
    sdw_wr(s, 0xC487, (u8)(reg >> 24));
    sdw_wr(s, 0xC486, (u8)(reg >> 16));
    sdw_wr(s, 0xC485, (u8)(reg >> 8));
    sdw_wr(s, 0xC484, (u8)reg);
    sdw_wr(s, 0xC482, 0xC0);
    for (a = 0xC48F; a >= 0xC48C; a--)
        v = (v << 8) | (u8)sdw_rd(s, a);
    return v;
}

/* MCU patch code: without the patch file Linux installs a "ret" stub (RISC-V 0x00008067) */
static void r20_patch(struct sdwdev *s)
{
    u32 a;
    if (s->priv[P20_ID] == ID_RT1321) {
        if (s->priv[P20_VER] == R21_VA2) return;
        a = 0x10008000UL;
    } else
        a = 0x10007000UL;
    sdw_wr(s, 0xC598, 0x00);
    sdw_wr(s, a, 0x67);
    sdw_wr(s, a + 1, 0x80);
    sdw_wr(s, a + 2, 0x00);
    sdw_wr(s, a + 3, 0x00);
    if (s->priv[P20_ID] == ID_RT1321) {
        sdw_wr(s, 0xD73C, 0x67);
        sdw_wr(s, 0xD73D, 0x80);
        sdw_wr(s, 0xD73E, 0x00);
        sdw_wr(s, 0xD73F, 0x00);
    }
}

/* the preset table: the patch goes in before the write to "hook"; with kr0 the MCU must
   report ready before PDE23 goes to PS0; every PDE23 request waits for the actual state */
static void r20_preset(struct sdwdev *s, const u32 *t, int n, u32 hook, int kr0)
{
    int i, k;
    u32 reg;
    u8 val;
    for (i = 0; i < n; i++) {
        reg = t[2 * i];
        val = (u8)t[2 * i + 1];
        if (reg == hook) r20_patch(s);
        if (kr0 && reg == R20_PDE23_REQ && val == PS0) {
            for (k = 0; k < 200 && sdw_rd(s, R20_KR0_READY) != 0x1F; k++) mdelay(1);
            if (k == 200) DBG("rt1320: MCU not ready\n");
        }
        if (reg == R20_PDE23_REQ)
            pde_set(s, R20_PDE23, val, 2000);
        else
            sdw_wr(s, reg, val);
    }
}

static void r20_ident(struct sdwdev *s)
{
    u32 id, ver, hv0, hv1, hv;
    int a, b;
    ver = (u32)(sdw_rd(s, R20_VERSION) & 0xFF);
    a = sdw_rd(s, R20_ID0);
    b = sdw_rd(s, R20_ID1);
    id = ((u32)(a & 0xFF) << 8) | (u32)(b & 0xFF);
    if (id != ID_RT1320 && id != ID_RT1321)
        id = s->part == 0x1321 ? ID_RT1321 : ID_RT1320;
    /* the high voltage block id reads right the second time */
    hv0 = r20_pr_read(s, R20_HV_ID0);
    hv1 = r20_pr_read(s, R20_HV_ID1);
    hv0 = r20_pr_read(s, R20_HV_ID0);
    hv1 = r20_pr_read(s, R20_HV_ID1);
    hv = (hv0 << 8) | hv1;
    if (id == ID_RT1321) {
        if (ver == 0x01) ver = R21_VA2;
        else if (hv == R21_HV_VA0) ver = 0;
        else if (hv == R21_HV_VA1) ver = 1;
    }
    s->priv[P20_ID] = id;
    s->priv[P20_VER] = ver;
    DBG("rt1320: id %04lx version %lu\n", id, ver);
}

static void r20_setvol(struct sdwdev *s)
{
    u32 lr = s->priv[P20_VOL], l = CDC_L(lr), r = CDC_R(lr), sl, sr;
    if (amp_side(s) == 1) r = l;
    else if (amp_side(s) == 2) l = r;
    sl = cdc_vstep(l, R20_VOL_STEPS, 750);
    sr = cdc_vstep(r, R20_VOL_STEPS, 750);
    sdw_wr16(s, AMP(ENT_FU21, CTL_VOL, 1), (u16)(0 - (R20_VOL_STEPS - sl) * 0xC0));
    sdw_wr16(s, AMP(ENT_FU21, CTL_VOL, 2), (u16)(0 - (R20_VOL_STEPS - sr) * 0xC0));
    /* level 0 mutes the channel */
    if (s->priv[P_ON]) fu21_mute(s, (u8)(l == 0), (u8)(r == 0));
}

static int r20_init(struct sdwdev *s)
{
    const u32 *t;
    int n, st;
    if (!s->priv[P20_DONE]) r20_ident(s);
    st = sdw_rd(s, R20_FUNC_STATUS);
    if ((st > 0 && (st & R20_NEEDS_INIT)) || !s->priv[P20_DONE]) {
        if (s->priv[P20_ID] == ID_RT1321) {
            switch (s->priv[P20_VER]) {
            case 0: t = r21_va0; n = ARRAY_SIZE(r21_va0) / 2; break;
            case 1: t = r21_va1; n = ARRAY_SIZE(r21_va1) / 2; break;
            default: t = r21_va2; n = ARRAY_SIZE(r21_va2) / 2; break;
            }
            r20_preset(s, t, n, 0x1000CD56UL, 0);
        } else if (s->priv[P20_VER] < R20_VC) {
            r20_preset(s, r20_vab, ARRAY_SIZE(r20_vab) / 2, 0x3FC2BFC7UL, 0);
        } else {
            r20_preset(s, r20_vc, ARRAY_SIZE(r20_vc) / 2, 0x3FC2BF83UL, 1);
        }
        sdw_wr(s, R20_FUNC_STATUS, R20_NEEDS_INIT);
    }
    s->priv[P20_DONE] = 1;
    s->priv[P_ON] = 0;
    sdw_wr(s, AMP(R20_PPU21, CTL_SEL, 0), r20_sel[amp_side(s)]);
    if (s->priv[P20_VOLSET]) r20_setvol(s);
    return 0;
}

static void r20_stream(struct sdwdev *s, int func, int on)
{
    int base;
    if (func != SF_SPK) return;
    if (on) {
        /* clock settings for the bus clock base the bus set (19.2 / 24 MHz otherwise) */
        base = sdw_rd(s, R20_CLK_BASE);
        if (base == 3 || base == 4) {
            sdw_wr(s, 0xC600, 0x07);
            sdw_wr(s, 0xC601, 0x80);
            sdw_wr(s, 0xC602, 0x0F);
        } else {
            sdw_wr(s, 0xC600, 0x04);
            sdw_wr(s, 0xC601, 0x83);
            sdw_wr(s, 0xC602, 0x1F);
        }
        sdw_wr(s, 0xC603, 0x40);
        sdw_wr(s, AMP(ENT_CS21, CTL_SEL, 0), FS_48K);
        pde_set(s, R20_PDE23, PS0, 2000);
        s->priv[P_ON] = 1;
        if (s->priv[P20_VOLSET]) r20_setvol(s);
        else fu21_mute(s, 0, 0);
    } else {
        s->priv[P_ON] = 0;
        fu21_mute(s, 1, 1);
        pde_set(s, R20_PDE23, PS3, 2000);
    }
}

static void r20_volume(struct sdwdev *s, int ctl, u32 lr)
{
    if (ctl != MX_MASTER) return;
    s->priv[P20_VOL] = lr;
    s->priv[P20_VOLSET] = 1;
    r20_setvol(s);
}

