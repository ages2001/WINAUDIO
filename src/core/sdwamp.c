/* sdwamp.c - Realtek SoundWire speaker amplifiers: RT1308 (SoundWire 1.1, vendor registers),
   RT1316, RT1318, RT1017 and RT1320 / RT1321 (SDCA smart amplifier function 4). Every
   amplifier receives the stereo stream on DP1 (RT1017: one channel) and picks its side with
   its own channel select register: with several amplifiers an even s->chan plays the left
   channel, an odd one the right channel. The I/V sense, echo reference and (RT1320) microphone
   capture ports are not used. Register sequences after the Linux rt1308-sdw, rt1316-sdw,
   rt1318-sdw, rt1017-sdca-sdw and rt1320-sdw drivers; the board specific biquad tables of
   soc_sdw_rt_amp (a few Dell models) are not applied, as Linux does on every other board. */
#include "sdw.h"

#define MFR_REALTEK     0x025D

/* SDCA controls of the smart amplifier function */
#define FN_AMP          4
#define CTL_REQ_PS      0x01        /* PDE requested power state */
#define CTL_ACT_PS      0x10        /* PDE actual power state */
#define CTL_MUTE        0x01        /* FU */
#define CTL_VOL         0x02        /* FU, 16 bit */
#define CTL_SEL         0x10        /* CS sample rate index, UDMPU cluster, PPU posture */
#define ENT_UDMPU21     0x02
#define ENT_FU21        0x03
#define ENT_CS21        0x21
#define FS_48K          0x09
#define PS0             0
#define PS3             3
#define AMP(ent, ctl, ch)   SDW_SDCA_CTL(FN_AMP, ent, ctl, ch)

/* priv[] of every chip */
#define P_ON            15          /* the speaker stream is powered */

static const struct sdwport dp1_stereo[] = { { SF_SPK, 1, 2, SPF_FULL } };
static const struct sdwport dp1_mono[] = { { SF_SPK, 1, 1, SPF_FULL } };

/* 0: stereo (single amplifier), 1: left channel, 2: right channel */
static int amp_side(struct sdwdev *s)
{
    if (s->namps < 2) return 0;
    return (s->chan & 1) ? 2 : 1;
}

/* SDCA power domain entity to a power state, waiting up to ms for the actual state */
static void pde_set(struct sdwdev *s, int ent, u8 ps, u32 ms)
{
    u32 i;
    sdw_wr(s, AMP(ent, CTL_REQ_PS, 0), ps);
    for (i = 0; i < ms; i++) {
        if (sdw_rd(s, AMP(ent, CTL_ACT_PS, 0)) == (int)ps) return;
        mdelay(1);
    }
    DBG("%s: PDE %02x not in PS%u\n", s->drv->name, ent, ps);
}

static void fu21_mute(struct sdwdev *s, u8 l, u8 r)
{
    sdw_wr(s, AMP(ENT_FU21, CTL_MUTE, 1), l);
    sdw_wr(s, AMP(ENT_FU21, CTL_MUTE, 2), r);
}

static void amp_off(struct sdwdev *s)
{
    if (s->priv[P_ON]) s->drv->stream(s, SF_SPK, 0);
}

