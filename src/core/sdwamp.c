/* clock of the bus (SoundWire 1.1 chip: no SCP_BusClock registers) to its divider */
static void r08_clock(struct sdwdev *s)
{
    u8 v;
    switch (s->busclk) {
    case 12000000UL: v = 0; break;
    case 6000000UL:  v = 1; break;
    case 9600000UL:  v = 2; break;
    case 2400000UL:  v = 4; break;
    case 12288000UL: v = 5; break;
    default:         v = 3; break;          /* 4.8 MHz */
    }
    sdw_wr(s, 0xE0, v);
    sdw_wr(s, 0xF0, v);
}

static int r08_init(struct sdwdev *s)
{
    static const u8 sel[3] = { 0, 1, 3 };
    int ver;
    sdw_wr(s, R08_RESET, 0);
    ver = sdw_rd(s, R08_HW_VER);
    DBG("rt1308: hw_ver %d\n", ver);
    sdw_seq(s, r08_init1, ARRAY_SIZE(r08_init1) / 2);
    sdw_wr(s, 0xC311, ver == R08_VER_C ? 0x7F : 0x4F);
    sdw_wr(s, 0xC300, ver == R08_VER_C ? 0x09 : 0x0B);
    sdw_seq(s, r08_init2, ARRAY_SIZE(r08_init2) / 2);
    sdw_upd(s, R08_DATA_PATH, 0x03, sel[amp_side(s)]);
    r08_clock(s);
    s->priv[P_ON] = 0;
    return 0;
}

static void r08_stream(struct sdwdev *s, int func, int on)
{
    if (func != SF_SPK) return;
    s->priv[P_ON] = (u32)on;
    if (on) {
        r08_clock(s);
        /* supplies: bias, LDOs, DAC, ADC, mixers, PLL2 */
        sdw_wr(s, R08_POWER0, 0xFF);
        sdw_upd(s, R08_POWER1, 0x37, 0x37);
        sdw_upd(s, R08_POWER2, 0x1F, 0x1F);
        sdw_upd(s, R08_DAC_SET3, 0xC0, 0x00);
        /* class D on, then the efuse calibration load */
        mdelay(30);
        sdw_upd(s, R08_PWR_STATUS, 0x03, 0x03);
        mdelay(40);
        sdw_wr(s, 0xC7F0, 0x04);
        sdw_wr(s, 0xC7F1, 0xFE);
        mdelay(100);
        sdw_wr(s, 0xC7F0, 0x44);
        mdelay(20);
        sdw_wr(s, 0xC240, 0x10);
    } else {
        sdw_upd(s, R08_PWR_STATUS, 0x03, 0x00);
        mdelay(150);
        sdw_upd(s, R08_DAC_SET3, 0xC0, 0xC0);
        sdw_upd(s, R08_POWER2, 0x1F, 0x00);
        sdw_upd(s, R08_POWER1, 0x37, 0x00);
        sdw_wr(s, R08_POWER0, 0x00);
    }
}

